export function aplicarDatasDemo(banco: Banco) {
  for (const consulta of banco.consultas) {
    const semana = DATAS_SEMANA[consulta.id]
    if (semana) {
      consulta.dataHora = isoNaSemana(semana[0], semana[1], semana[2] ?? 0)
      continue
    }
    const referencia = DATAS_CONSULTA[consulta.id]
    if (!referencia) continue
    consulta.dataHora = isoEm(referencia[0], referencia[1], referencia[2] ?? 0)
  }

  const bloqueio = banco.bloqueios.find(
    (item) => item.id === 'bloq-paulo-almoco',
  )
  if (bloqueio) {
    bloqueio.inicio = isoNaSemana(3, 12)
    bloqueio.fim = isoNaSemana(3, 13, 30)
  }

  const vacinaLuna = banco.vacinas.find((item) => item.id === 'vac-luna-v4')
  if (vacinaLuna) vacinaLuna.proximaDose = diaIso(15)

  const vacinaLola = banco.vacinas.find((item) => item.id === 'vac-lola-v10')
  if (vacinaLola) vacinaLola.proximaDose = diaIso(8)
}
